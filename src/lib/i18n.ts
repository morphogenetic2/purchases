function normalizeLocale(value: string | null | undefined): Locale {
    const normalized = (value || "").toLowerCase();
    if (normalized.startsWith("es")) return "es";
    if (normalized.startsWith("ca")) return "ca";
    return FALLBACK_LOCALE;
}

function readInitialLocale(): Locale {
    if (!browser) return FALLBACK_LOCALE;

    try {
        const stored = window.localStorage.getItem(STORAGE_KEY);
        if (stored) return normalizeLocale(stored);
        return normalizeLocale(window.navigator.language);
    } catch {
        return FALLBACK_LOCALE;
    }
}

function format(template: string, variables?: Variables): string {
    if (!variables) return template;
    return template.replace(/\{\{\s*(\w+)\s*\}\}/g, (_, key: string) => {
        const value = variables[key];
        return value === undefined || value === null ? "" : String(value);
    });
}

function translate(localeValue: Locale, key: string, variables?: Variables): string {
    const selected = messages[localeValue]?.[key];
    const fallback = messages[FALLBACK_LOCALE]?.[key];
    return format(selected ?? fallback ?? key, variables);
}

export const locale = writable<Locale>(readInitialLocale());

if (browser) {
    locale.subscribe((value) => {
        document.documentElement.lang = value;
        try {
            window.localStorage.setItem(STORAGE_KEY, value);
        } catch {
            // Ignore storage quota/privacy errors.
        }
    });
}

export function setLocale(value: Locale) {
    locale.set(value);
}

export const localeOptions: Array<{ value: Locale; label: string }> = [
    { value: "en", label: "EN" },
    { value: "es", label: "ES" },
    { value: "ca", label: "CA" },
];

export const t = derived(locale, ($locale) => {
    return (key: string, variables?: Variables) =>
        translate($locale, key, variables);
});

export function localizeStatus(status: string, translateFn: Translator): string {
    const key = STATUS_KEY_BY_VALUE[status];
    if (!key) return status;
    return translateFn(key);
}

export function localizeGroupBy(value: string, translateFn: Translator): string {
    const key = GROUP_BY_KEY_BY_VALUE[value];
    if (!key) return value;
    return translateFn(key);
}
